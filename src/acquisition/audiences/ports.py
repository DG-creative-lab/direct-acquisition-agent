from typing import Protocol

from .domain import Snapshot, DatasetVersion, AudienceTaxonomy, ProfiledSnapshot


class AudienceStore(Protocol):
    def put(self, snapshot: Snapshot) -> str: ...
    def get(self, organization: str, snapshot_id: str) -> Snapshot: ...


class AudienceSource(Protocol):
    def listing(self, organization: str) -> tuple['DatasetVersion', ...]: ...
    def read(self, organization: str, dataset_id: str, version: str, checksum: str, manifest_id: str) -> tuple['DatasetVersion', Snapshot]: ...


class ProfileFixtureAudience(Protocol):
    def snapshot(self, organization: str, taxonomy: AudienceTaxonomy, size: int, seed: int, as_of: str) -> ProfiledSnapshot: ...
    def snapshot_identity(self, organization: str, taxonomy: AudienceTaxonomy, size: int, seed: int, as_of: str) -> str: ...


class ContactSource(Protocol):
    def read(self, organization: str, connection_key: str, version: int): ...
    def identity(self, organization: str, connection_key: str, version: int) -> str: ...


class ContactDirectoryStore(Protocol):
    def refresh(self, organization: str, request_id: str, snapshot) -> dict: ...
    def prepare(self, organization: str, request_id: str, snapshot, channel: str, purpose: str) -> dict: ...
    def object(self, organization: str, request_id: str, contact_id: str, channel: str, purpose: str, reason: str) -> dict: ...
    def inspect(self, organization: str, assessment_id: str) -> dict: ...
