from typing import Protocol

from acquisition.campaigns import SequenceConnection
from .domain import DispatchClaim, SimulationReceipt


class SimulationTransport(Protocol):
    connection: SequenceConnection
    configuration_id: str
    def submit(self, intent: dict) -> SimulationReceipt: ...


class EngagementStore(Protocol):
    def start(self, organization: str, request_id: str, proposal_id: str, configuration: dict, approval_id: str | None = None) -> dict: ...
    def claim(self, organization: str, simulation_id: str, configuration: dict, lease_seconds: int) -> DispatchClaim | None: ...
    def settle(self, claim: DispatchClaim, receipt: SimulationReceipt) -> None: ...
    def inspect(self, organization: str, simulation_id: str) -> dict: ...
    def observe(self, organization: str, request_id: str, simulation_id: str, step_id: str,
                provider_effect_id: str, kind: str, occurred_at: float) -> dict: ...
    def stop(self, organization: str, request_id: str, simulation_id: str) -> dict: ...


class SequenceEffectAuthority(Protocol):
    """The adapter supplies the caller's transaction to the authority port."""
    def authorize(self, transaction, organization: str, proposal_id: str, approval_id: str) -> dict: ...
    def bind(self, transaction, organization: str, simulation_id: str, proposal_id: str, approval_id: str) -> None: ...
    def authorize_simulation(self, transaction, organization: str, simulation_id: str, proposal_id: str) -> dict: ...
    def status(self, transaction, organization: str, simulation_id: str, proposal_id: str) -> dict: ...
