from typing import Protocol

from .domain import ReviewPolicy


class ReviewStore(Protocol):
    def register_actor(self, organization: str, actor: str, roles: tuple[str, ...], enabled: bool = True) -> dict: ...
    def activate(self, organization: str, actor: str, request_id: str, pack: dict, policy: ReviewPolicy) -> dict: ...
    def evidence(self, organization: str) -> dict | None: ...
    def open_case(self, organization: str, run_id: str, actor: str) -> dict: ...
    def view(self, organization: str, case_id: str) -> dict: ...
    def prepare(self, organization: str, case_id: str, expected_subject: str, actor: str, request_id: str) -> dict: ...
    def decide(self, organization: str, case_id: str, expected_subject: str, actor: str,
               decision: str, request_id: str, reason: str, ttl_seconds: int) -> dict: ...
    def revoke(self, organization: str, case_id: str, approval_id: str, actor: str, request_id: str, reason: str) -> dict: ...
    def suppress(self, organization: str, actor: str, request_id: str, business_id: str, reason: str) -> dict: ...
    def propose(self, organization: str, case_id: str, expected_subject: str, draft_id: str,
                actor: str, request_id: str, audience_epoch: int, evidence_epoch: int, kind: str = "replace") -> dict: ...
    def handoff(self, organization: str, case_id: str, approval_id: str, actor: str, request_id: str) -> dict: ...


class ProposalBuilder(Protocol):
    def refresh(self, organization: str, draft_id: str, suppressions: tuple[str, ...], operation: str) -> str: ...
