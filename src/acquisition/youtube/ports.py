from typing import Protocol

from .domain import YouTubeScope


class YouTubeAuthority(Protocol):
    def require(self, scope: YouTubeScope, actor: str, operation: str) -> int: ...


class ComparisonAssets(Protocol):
    def manifest(self, contexts: list[str]) -> dict: ...


class DecisionInputs(Protocol):
    """Trusted authored inputs, never model-supplied identity or cost."""
    def load(self, scope: YouTubeScope) -> dict: ...


class RankingReceipts(Protocol):
    """Recorded offline proposals only. Live serving needs reasoning admission."""
    def rank(self, frozen: dict) -> dict: ...


class YouTubeStore(Protocol):
    def store_identity(self) -> str: ...
    def interactions(self, scope: YouTubeScope, actor: str, conversation_id: str) -> list[dict]: ...
    def message(self, scope: YouTubeScope, actor: str, command: dict) -> dict: ...
    def read(self, scope: YouTubeScope, actor: str, campaign_id: str) -> dict: ...
    def command(self, scope: YouTubeScope, actor: str, operation: str, command: dict) -> dict: ...
    def preview(self, scope: YouTubeScope, actor: str, context: str, fingerprint: str) -> dict: ...
    def media(self, scope: YouTubeScope, actor: str, name: str, fingerprint: str) -> bytes: ...
    def resume_command(self, scope: YouTubeScope, actor: str, operation_id: str, conversation_id: str) -> dict: ...
