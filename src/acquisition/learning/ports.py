from pathlib import Path
from typing import Protocol


class CohortSource(Protocol):
    def accepted(self, organization: str, case_id: str) -> dict: ...


class ReportSource(Protocol):
    def read(self, path: Path) -> dict: ...


class LearningStore(Protocol):
    def open(self, organization: str, actor: str, request_id: str, proposal: dict) -> dict: ...
    def ingest(self, organization: str, actor: str, request_id: str, cohort_id: str, batch: dict) -> dict: ...
    def ingest_report(self, organization: str, actor: str, request_id: str, cohort_id: str, report: dict) -> dict: ...
    def report_snapshot(self, organization: str, cohort_id: str, report_id: str) -> dict: ...
    def finalize(self, organization: str, actor: str, request_id: str, cohort_id: str, complete_through: float) -> dict: ...
    def view(self, organization: str, cohort_id: str) -> dict: ...
    def hypothesis_source(self, organization: str, cohort_id: str) -> dict: ...
    def memory(self, organization: str, segment: str) -> dict: ...
    def memory_snapshot(self, organization: str, segments: tuple[str, ...]) -> dict[str, dict]: ...
