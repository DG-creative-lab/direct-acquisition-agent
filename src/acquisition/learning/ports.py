from pathlib import Path
from typing import Protocol


class CohortSource(Protocol):
    def accepted(self, organization: str, case_id: str) -> dict: ...


class ReportSource(Protocol):
    def read(self, path: Path) -> dict: ...
    def parse(self, raw: bytes) -> dict: ...


class ReportMonitoringStore(Protocol):
    def reject(self, organization, actor, request_id, payload) -> bool: ...
    def start(self, organization, actor, request_id, cohort_id, first_check, interval, reports) -> dict: ...
    def update(self, organization, actor, request_id, cohort_id, expected_revision, status, interval=None) -> dict: ...
    def status(self, organization, cohort_id) -> dict | None: ...
    def claim(self, organization, cohort_id, *, standalone=False, expected_position=None) -> str | None: ...
    def import_claim(self, organization, cohort_id, token) -> bool: ...
    def finish(self, organization, cohort_id, token) -> None: ...
    def block(self, organization, cohort_id, token, detail) -> None: ...


class LearningStore(Protocol):
    def open(self, organization: str, actor: str, request_id: str, proposal: dict) -> dict: ...
    def ingest(self, organization: str, actor: str, request_id: str, cohort_id: str, batch: dict, *, simulate=False) -> dict: ...
    def ingest_report(self, organization: str, actor: str, request_id: str, cohort_id: str, report: dict) -> dict: ...
    def report_snapshot(self, organization: str, cohort_id: str, report_id: str) -> dict: ...
    def finalize(self, organization: str, actor: str, request_id: str, cohort_id: str, complete_through: float) -> dict: ...
    def view(self, organization: str, cohort_id: str) -> dict: ...
    def hypothesis_source(self, organization: str, cohort_id: str) -> dict: ...
    def memory(self, organization: str, segment: str) -> dict: ...
    def memory_snapshot(self, organization: str, segments: tuple[str, ...]) -> dict[str, dict]: ...


class ExternalOutcomeStore(Protocol):
    def identity(self) -> str: ...
    def listing(self, organization, **page) -> dict: ...
    def preview(self, organization, operation, **value) -> dict: ...
    def not_committed(self, organization, actor, operation, key) -> bool: ...
    def register(self, organization: str, actor: str, request_id: str, payload: dict, *, selection=None, preview_id=None) -> dict: ...
    def ingest(self, organization: str, actor: str, request_id: str, cohort_id: str, payload: dict, *, preview_id=None) -> dict: ...
    def finalize(self, organization: str, actor: str, request_id: str, cohort_id: str, *, preview_id=None) -> dict: ...
    def view(self, organization: str, cohort_id: str) -> dict: ...
    def snapshot(self, organization: str, cohort_id: str, report_id: str) -> dict: ...
    def receipt(self, organization: str, actor: str, operation: str, request_id: str) -> dict: ...
