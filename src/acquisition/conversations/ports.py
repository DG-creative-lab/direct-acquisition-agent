from typing import Protocol
from collections.abc import Callable
from .admission import AdmissionIntent, AdmissionReceipt
from acquisition.reasoning import ModelConfig


class AdmissionStore(Protocol):
    """Execution stays paused until every caller and effect fence is ready.

    admit verifies authoritative sources/consent/parent and operation uniqueness,
    then commits intent, ownership, tasks and receipt in one transaction. A
    cached receipt observes admission; workers recheck current authorization.
    """
    def request_planning(self, organization: str, conversation_id: str, request_id: str, revision: int,
                         context: dict, *, fixture: bool, allow_model: bool,
                         model_config: ModelConfig | None = None) -> AdmissionIntent: ...
    def admit(self, intent: AdmissionIntent, now: float) -> AdmissionReceipt: ...
    def request_workflow(self, organization: str, request_id: str, kind: str, references: dict, *,
                         allow_model: bool, model_config: ModelConfig | None = None) -> AdmissionIntent: ...
    def get_request(self, organization: str, request_id: str) -> AdmissionIntent | None: ...
    def pending_requests(self, organization: str) -> list[AdmissionIntent]: ...
    def find_request(self, organization: str, request_id: str) -> AdmissionReceipt | None: ...
    def get(self, organization: str, admission_id: str) -> AdmissionIntent: ...


class ExecutionStore(Protocol):
    def view(self, organization: str, conversation_id: str) -> dict: ...
    def for_run(self, organization: str, run_id: str) -> dict | None: ...
    def pending(self, organization: str, run_id: str) -> bool: ...
    def stop(self, organization: str, conversation_id: str, request_id: str, revision: int, now: float) -> dict: ...
    def descendant(self, organization: str, campaign_id: str, parent_run_id: str) -> dict: ...
    def stopped_checkpoints(self, organization: str) -> list[dict]: ...
    def unresolved(self, organization: str) -> list[dict]: ...
    def resolve_independent(self, organization: str, request_id: str, inputs: dict, now: float) -> dict: ...


class ConversationStore(Protocol):
    def create(self, organization: str, request_id: str, title: str, now: float) -> str: ...
    def listing(self, organization: str) -> list[dict]: ...
    def snapshot(self, organization: str, conversation_id: str) -> dict: ...
    def append(self, organization: str, conversation_id: str, request_id: str, expected_revision: int, content: str, now: float) -> dict: ...
    def admit(self, organization: str, conversation_id: str, request_id: str, expected_revision: int, context: dict,
              now: float, preflight: Callable[[dict], None]) -> dict: ...


class PreparationStore(Protocol):
    def request(self, organization: str, request_id: str) -> dict | None: ...
    def for_revision(self, organization: str, conversation_id: str, revision: int) -> dict | None: ...
    def create(self, organization: str, request_id: str, value: dict) -> dict: ...
    def get(self, organization: str, preparation_id: str) -> dict: ...
    def listing(self, organization: str, conversation_id: str | None = None) -> list[dict]: ...
    def update(self, organization: str, prior: dict, status: str, detail: str | None, *, run_id: str | None = None) -> dict: ...


class PreparationHost(Protocol):
    def freeze_preparation_plan(self, organization: str, conversation_id: str, request_id: str, revision: int, fixture: bool) -> dict: ...
    def admit_preparation_plan(self, organization: str, row: dict) -> str: ...
    def preparation_source(self, organization: str, conversation_id: str) -> dict: ...
    def step_preparation_plan(self, organization: str, row: dict) -> dict: ...
    def step_preparation_campaign(self, organization: str, row: dict, plan: dict) -> dict: ...
    def preparation_audience_selected(self, organization: str, row: dict, plan: dict) -> bool: ...
    def preparation_generation(self, organization: str, row: dict) -> dict | None: ...


class AudienceSelectionStore(Protocol):
    def request(self, organization: str, request_id: str) -> dict | None: ...
    def get(self, organization: str, conversation_id: str, revision: int) -> dict | None: ...
    def select(self, organization: str, request_id: str, inputs: dict, receipt: dict, snapshot, now: float) -> dict: ...


class ConversationActionStore(Protocol):
    def request(self, organization: str, conversation_id: str, request_id: str) -> dict | None: ...
    def get(self, organization: str, action_id: str) -> dict: ...
    def listing(self, organization: str, conversation_id: str | None = None) -> list[dict]: ...
    def admit(self, organization: str, conversation_id: str, request_id: str, frozen: dict, now: float) -> dict: ...
    def confirm(self, organization: str, action_id: str, request_id: str, target_id: str, expected_revision: int, now: float) -> dict: ...
