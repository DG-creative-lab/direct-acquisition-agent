from typing import Protocol
from collections.abc import Callable


class ConversationStore(Protocol):
    def create(self, organization: str, request_id: str, title: str, now: float) -> str: ...
    def listing(self, organization: str) -> list[dict]: ...
    def snapshot(self, organization: str, conversation_id: str) -> dict: ...
    def append(self, organization: str, conversation_id: str, request_id: str, expected_revision: int, content: str, now: float) -> dict: ...
    def admit(self, organization: str, conversation_id: str, request_id: str, expected_revision: int, context: dict,
              now: float, preflight: Callable[[dict], None]) -> dict: ...
