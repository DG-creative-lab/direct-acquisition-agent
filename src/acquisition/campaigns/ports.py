from dataclasses import dataclass
from typing import Protocol

from .domain import Draft, CampaignProfile


@dataclass(frozen=True)
class DraftLease:
    run_id: str
    task_id: str
    token: str


class DraftStore(Protocol):
    def put(self, organization: str, operation_id: str, draft: Draft, *, lease: DraftLease | None = None) -> str: ...
    def get(self, organization: str, draft_id: str) -> Draft: ...


class CampaignProfileSource(Protocol):
    def campaign_profile(self, organization: str, key: str, version: str) -> CampaignProfile: ...


class ProfileProposalStore(Protocol):
    def find(self, organization: str, request_id: str) -> Draft | None: ...
    def publish(self, organization: str, request_id: str, snapshot, bundles: tuple, draft: Draft) -> str: ...
    def get(self, organization: str, identity: str) -> Draft: ...


class SequenceProposalStore(Protocol):
    def prepare(self, organization: str, request_id: str, request) -> dict: ...
    def inspect(self, organization: str, proposal_id: str) -> dict: ...


class FollowupStore(Protocol):
    def get(self, organization: str, identity: str) -> dict: ...
    def put(self, organization: str, request: str, proposal: dict) -> dict: ...
    def excluded(self, organization: str) -> set[str]: ...
    def check(self, organization: str, proposal: dict, campaign_id: str) -> None: ...
    def listing(self, organization: str, parent_id: str) -> list[dict]: ...
class CampaignIntakeStore(Protocol):
    """Atomic intake revisions and original request receipts, scoped by organization."""
    def identity(self) -> str: ...
    def save(self, organization: str, request_id: str, inputs: dict, now: float) -> dict: ...
    def get(self, organization: str, kind: str, identity: str, revision: int | None) -> dict: ...
    def listing(self, organization: str, kind: str, after_id: str, limit: int) -> list[dict]: ...
