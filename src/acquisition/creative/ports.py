from typing import Protocol

from .domain import Creative
from .profiles import ProductProfile


class CreativeMemory(Protocol):
    def preferences(self, organization: str) -> list[dict]: ...
    def change_preference(self, organization: str, source_organization: str, conversation_id: str,
                          comment_id: str, preference_id: str, action: str, expected_revision: int,
                          segments: list[str], preferred: str, avoid: str, reason: str,
                          confirmed: bool, actor: str, request_id: str, now: float) -> dict: ...
    def remember(self, organization: str, segment: str, preferred: str, avoid: str, reason: str) -> str: ...
    def examples(self, organization: str, segment: str) -> list[dict]: ...
    def examples_snapshot(self, organization: str, segments: tuple[str, ...], fallbacks: dict | None = None) -> dict[str, list[dict]]: ...
    def put_context(self, organization: str, context: dict) -> str: ...
    def get_context(self, organization: str, context_id: str) -> dict: ...
    def get_catalogue(self, organization: str, operation_id: str) -> tuple[Creative, ...] | None: ...
    def put_catalogue(self, organization: str, operation_id: str, variants: tuple[Creative, ...]) -> None: ...


class ProductEvidenceSource(Protocol):
    def product_profile(self, organization: str, identity: str) -> ProductProfile: ...
    def product_material(self, organization: str, identity: str) -> dict: ...
