"""Compatibility journal operations, separate from environment authority.

Session records are raw historical payloads so damaged disposable projections
can still be skipped by their consumer. No operation grants execution authority.
New session candidates are frozen before admission. Replays retain the original
payload. Connections, callbacks and SQL never cross this boundary.
"""
from typing import ContextManager, Protocol


class WorkspaceStorageUnavailable(OSError):
    """Local persistence is unavailable; original durable work can be recovered."""


class WorkspaceStorageFaults(Protocol):
    def guard(self) -> ContextManager[None]: ...


class WorkspaceControlStore(Protocol):
    def sessions(self, *, reverse: bool = False) -> list[dict]: ...
    def session(self, identity: str) -> dict | None: ...
    def project_session(self, session: dict) -> None: ...
    def save_session(self, session: dict) -> None: ...
    def restore_case_links(self, organization: str, identity: str, run: str, case: str) -> None: ...
    def checkpoint_block(self, organization: str, run: str) -> str | None: ...
    def set_checkpoint_block(self, organization: str, run: str, code: str | None) -> None: ...
    def revision_block(self, organization: str, revision: str) -> str | None: ...
    def set_revision_block(self, organization: str, revision: str, code: str | None) -> None: ...
    def draft_request(self, conversation: str, request: str) -> dict | None: ...
    def admit_draft(self, conversation: str, request: str, fingerprint: str, session: dict) -> None: ...
    def admit_followup(self, organization: str, request: str, fingerprint: str, identity: str,
                       session_fingerprint: str, session: dict | None) -> None: ...
    def create_session(self, identity: str, fingerprint: str, session: dict | None) -> None: ...
    def command(self, organization: str, identity: str, request: str) -> dict | None: ...
    def begin_command(self, organization: str, identity: str, request: str, fingerprint: str,
                      *, next_due: float | None = None) -> dict: ...
    def complete_command(self, organization: str, identity: str, request: str) -> None: ...
